"""Builds line_paths.py: travel time of every leg between consecutive stops.

app.py uses these saved times before anyone presses Refresh, and when HERE is
not called or fails. Without them, legs are estimated from coordinates.

  export HERE_API_KEY=your_key
  python build_paths.py 22 50        # the lines to build
  python build_paths.py 22 --estimate  # no key, or offline: coordinates only

Cost: one HERE request per leg and direction, printed before starting. Lines
already in line_paths.py are kept; the lines you name are rebuilt. Run again
when a line's stops change.
"""

import argparse
import os
from pprint import pformat
import runpy
import time

import requests

from lines import DWELL_SECONDS, LINES, estimate_leg, straight_line_meters

HERE_API_KEY = os.getenv("HERE_API_KEY", "")
# A leg longer than this multiple of the straight line is a detour. Stop
# coordinates can be approximate, so HERE may snap them to the wrong street.
MAX_DETOUR_RATIO = 2.5
# Below this straight-line distance the ratio check is skipped: snapping to
# the nearest road dominates very short legs.
MIN_CHECK_METERS = 150
REQUEST_DELAY = 0.2  # pause between HERE requests


def here_leg(a, b):
  """(seconds, meters) from HERE, or None when unusable."""
  params = [("transportMode", "car"), ("origin", f"{a['lat']},{a['lng']}"),
            ("destination", f"{b['lat']},{b['lng']}"), ("return", "summary"), ("apiKey", HERE_API_KEY)]
  try:
    data = requests.get("https://router.hereapi.com/v8/routes", params=params, timeout=10).json()
  except Exception as e:
    # Type only: the error text holds the URL, and the URL holds the HERE key.
    print(f"  request failed: {type(e).__name__}")
    return None
  if not data.get("routes"):
    print(f"  no route: {data.get('title') or data}")
    return None
  sections = data["routes"][0]["sections"]
  seconds = sum(s["summary"].get("duration", 0) for s in sections)
  meters = sum(s["summary"].get("length", 0) for s in sections)
  straight = straight_line_meters(a, b)
  if straight >= MIN_CHECK_METERS and meters > MAX_DETOUR_RATIO * straight:
    print(f"  detour: {meters}m for {straight:.0f}m straight")
    return None
  return round(seconds + DWELL_SECONDS), round(meters)  # HERE car time has no dwell


def build_direction(ref, direction, use_here):
  stops, legs = LINES[ref][direction]["stations"], []
  for a, b in zip(stops, stops[1:]):
    print(f"{ref}/{direction} {a['no']} -> {b['no']}")
    result = here_leg(a, b) if use_here else None
    if use_here:
      time.sleep(REQUEST_DELAY)
    seconds, meters = result or tuple(round(x) for x in estimate_leg(a, b))
    # app.py matches legs by name, because numbers change with the data.
    legs.append({"from": a["no"], "to": b["no"], "from_name": a["name"], "to_name": b["name"],
                 "seconds": seconds, "meters": meters, "source": "here" if result else "estimate"})
  return {"legs": legs}


def main():
  parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
  parser.add_argument("lines", nargs="+", help="line numbers")
  parser.add_argument("--estimate", action="store_true", help="skip HERE, estimate every leg from coordinates")
  parser.add_argument("--out", default="line_paths.py", help="output file")
  args = parser.parse_args()
  if not args.estimate and not HERE_API_KEY:
    raise SystemExit("HERE_API_KEY is empty. Set it, or pass --estimate.")

  refs = args.lines
  for ref in refs:
    if ref not in LINES:
      raise SystemExit(f"Line {ref} has no stops.")
  legs = sum(len(d["stations"]) - 1 for ref in refs for d in LINES[ref].values())
  print(f"{len(refs)} line(s), {legs} legs" + ("" if args.estimate else f" = {legs} HERE requests"))

  paths = runpy.run_path(args.out).get("LINE_PATHS", {}) if os.path.exists(args.out) else {}
  for ref in refs:
    paths[ref] = {k: build_direction(ref, k, not args.estimate) for k in LINES[ref]}
  with open(args.out, "w", encoding="utf-8") as f:
    f.write('"""Generated by build_paths.py. Do not edit by hand."""\n\n'
            f"LINE_PATHS = {pformat(dict(sorted(paths.items())), width=100, sort_dicts=False)}\n")
  for ref in refs:
    for key, d in paths[ref].items():
      total = sum(leg["seconds"] for leg in d["legs"])
      estimated = sum(leg["source"] == "estimate" for leg in d["legs"])
      print(f"{ref}/{key}: {len(d['legs'])} legs, {total // 60} min total, {estimated} estimated")
  print(f"Wrote {args.out}")


if __name__ == "__main__":
  main()
